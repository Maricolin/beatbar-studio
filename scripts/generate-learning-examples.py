"""Generate deterministic, distributable learning assets; never touches user data."""
from __future__ import annotations

import argparse
import io
import json
import math
import struct
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RATE = 22_050
DURATION = 8


def encode_json(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def build_assets() -> dict[str, bytes]:
    times = [0.25 + index * 0.5 for index in range(16)]
    levels = [0.85, 0.35, 0.55, 0.35]
    pcm = bytearray(RATE * DURATION * 2)
    for sample in range(RATE * DURATION):
        time = sample / RATE
        index = math.floor((time - 0.25) / 0.5)
        age = time - (0.25 + index * 0.5)
        value = 0.0
        if 0 <= index < 16 and 0 <= age < 0.09:
            value = levels[index % 4] * math.exp(-age / 0.018) * (
                0.82 * math.sin(2 * math.pi * 150 * age)
                + 0.18 * math.sin(2 * math.pi * 1800 * age)
            )
        struct.pack_into("<h", pcm, sample * 2, round(max(-1, min(1, value)) * 32767))
    audio = io.BytesIO()
    with wave.open(audio, "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(pcm)
    beats = [{"time": time, "strength": [0.95, 0.4, 0.7, 0.4][i % 4]} for i, time in enumerate(times)]
    style = {"color": "#b7f56c", "secondaryColor": "#67dce8", "barColor": "#30363e", "backgroundColor": "#111820", "colorMode": "alternate", "position": 0.82, "barWidth": 0.8, "barHeight": 44, "speed": 2, "marker": 0.15, "pattern": "circle", "motion": "right-left", "hitEffect": "ring", "hitDuration": 0.45, "effectIntensity": 1, "beatScale": 1, "trackType": "classic", "markerPattern": "line", "markerColor": "#ffffff", "markerScale": 1, "dbFloor": -48, "dbCeiling": -6}
    variants = [
        ("classic-120", "经典双色轨道", "16 拍 · 120 BPM · 圆点双色交替", beats, style, 120, "composite"),
        ("converge-120", "双侧汇合与命中标记", "16 拍 · 120 BPM · 两侧竖线汇合", beats, {**style, "trackType": "converge", "pattern": "bar", "motion": "meet", "marker": 0.5, "color": "#ff9c74", "secondaryColor": "#f7d774", "hitEffect": "flash"}, 120, "composite"),
        ("green-half-time", "隔拍绿幕轨道", "8 拍 · 60 BPM · 用于剪辑抠像叠加", beats[::2], {**style, "colorMode": "solid", "pattern": "diamond"}, 60, "green"),
    ]
    assets = {"beatbar-120.wav": audio.getvalue(), "beatbar-120.beats.json": encode_json({"version": 1, "beats": beats})}
    entries = []
    for key, title, summary, points, settings, bpm, mode in variants:
        project = {"version": 1, "media": None, "beats": points, "style": settings, "bpm": bpm, "exportSettings": {"filename": title, "resolution": "640x360", "fps": 24, "mode": mode, "includeAudio": True}, "editorSettings": {"inputs": {"fillStart": "0.25", "fillEnd": "7.75", "sensitivity": "55", "minInterval": "0.20", "band": "40,3000", "analysisMode": "onsets", "previewMode": mode}, "tab": "auto", "playhead": 0, "zoom": 1, "scrollLeft": 0, "selected": -1}}
        assets[key + ".json"] = encode_json(project)
        entries.append({"id": key, "title": title, "summary": summary, "file": key + ".json", "beatCount": len(points), "bpm": bpm})
    actions = []
    for time in times:
        actions.extend([{"at": round((time - 0.1) * 1000), "pos": 0}, {"at": round(time * 1000), "pos": 100}])
    assets["beatbar-120.funscript"] = encode_json({"version": "1.0", "inverted": False, "range": 100, "actions": actions})
    assets["catalog.json"] = encode_json({"audio": "beatbar-120.wav", "duration": DURATION, "bpm": 120, "beatCount": 16, "examples": entries})
    return assets


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes without writing")
    args = parser.parse_args()
    folder = ROOT / "docs" / "examples"
    assets = build_assets()
    mismatches = []
    for name, content in assets.items():
        path = folder / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                mismatches.append(name)
        else:
            folder.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if mismatches:
        raise SystemExit("Learning assets are missing or stale: " + ", ".join(mismatches))
    print(f"{'Verified' if args.check else 'Generated'} {len(assets)} learning assets")


if __name__ == "__main__":
    main()
